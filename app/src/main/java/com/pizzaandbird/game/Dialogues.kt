        val pools = ArrayList<List<String>>(3)
        if (c.night) {
            pools.add(PROFESSOR_NIGHT)
        } else {
            PROFESSOR_SEASON[c.season]?.let { pools.add(it) }
            PROFESSOR_WEATHER[c.weather]?.let { pools.add(it) }
        }
        val line = pickFrom(pickFrom(pools)) ?: return ""
        return "\n\"$line\""
    }

    private fun <T> pickFrom(list: List<T>?): T? =
        if (list.isNullOrEmpty()) null else list[rnd.nextInt(list.size)]
}
